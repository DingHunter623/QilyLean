#!/usr/bin/env node
'use strict';
const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const image=path.join(root,'qilylean','c919-strategy-hero-v10.svg');
const topPatch=path.join(root,'qilylean','c919-patch-topleft-v10.webp');
const tailPatch=path.join(root,'qilylean','c919-patch-tail-v10.webp');
const bottomPatch=path.join(root,'qilylean','c919-patch-bottomq-v10.webp');
function assert(ok,msg){if(!ok)throw new Error(msg);}
assert((html.match(/<!-- QILY-C919-STRATEGY-HERO:START -->/g)||[]).length===1,'C919 hero start marker must exist once');
assert((html.match(/<!-- QILY-C919-STRATEGY-HERO:END -->/g)||[]).length===1,'C919 hero end marker must exist once');
const mainPos=html.search(/<main\b[^>]*>/i), heroPos=html.indexOf('<!-- QILY-C919-STRATEGY-HERO:START -->'), oldHeroPos=html.indexOf('<section class="hero">');
assert(mainPos>=0&&heroPos>mainPos,'C919 hero must be inside main');
assert(oldHeroPos<0||heroPos<oldHeroPos,'C919 hero must be homepage number-one content');
assert(fs.existsSync(image)&&fs.statSync(image).size>1000,'C919 corrected SVG strategy image missing');
assert(fs.existsSync(topPatch)&&fs.statSync(topPatch).size>1000,'C919 official top-left logo patch missing');
assert(fs.existsSync(tailPatch)&&fs.statSync(tailPatch).size>1000,'C919 exact tail Q icon patch missing');
assert(fs.existsSync(bottomPatch)&&fs.statSync(bottomPatch).size>1000,'C919 exact bottom Q icon patch missing');
const svg=fs.readFileSync(image,'utf8');
assert(svg.includes('/qilylean/c919-patch-topleft-v10.webp'),'corrected SVG missing official QilyLean logo patch');
assert(svg.includes('/qilylean/c919-patch-tail-v10.webp'),'corrected SVG missing exact tail Q patch');
assert(svg.includes('/qilylean/c919-patch-bottomq-v10.webp'),'corrected SVG missing exact bottom Q patch');
assert(svg.includes('id="c-l4"')&&svg.includes('id="c-r1"'),'corrected SVG missing screen-left/right business-stack swap');
assert(html.includes('src="/qilylean/c919-strategy-hero-v10.svg"'),'C919 corrected image path missing');
assert(html.includes('左翼承载<strong>1～3：新工厂／新产线规划、精益改善项目交付、目视化项目设计与交付</strong>'),'left wing must be locked to businesses 1-3');
assert(html.includes('右翼承载<strong>4～6：数字化工厂、APP软件开发、官网建设</strong>'),'right wing must be locked to businesses 4-6');
assert(!html.includes('左翼承载<strong>数字化工厂、APP软件开发、官网建设</strong>'),'reversed semantic left-wing mapping returned');
assert(!html.includes('右翼承载<strong>新工厂／新产线规划、精益改善项目交付、目视化项目设计与交付</strong>'),'reversed semantic right-wing mapping returned');
assert(html.includes('.qily-c919-soul{width:min(1420px,calc(100% - 24px));margin:28px auto 0;'),'C919 soul summary must be widened and moved below image');
assert(html.includes('助企业高质量发展'),'customer strategic axis missing');
assert(html.includes('启力精益展翼远航'),'brand strategic axis missing');
assert(html.includes('这不是一张装饰性的飞机图，而是一张启力精益面向制造企业的战略蓝图。'),'soul summary missing');
['新工厂／新产线规划','精益改善项目交付','目视化项目设计与交付','数字化工厂','APP软件开发','官网建设'].forEach(name=>assert(html.includes(name),`locked business missing: ${name}`));
assert(!html.includes('三大核心业务'),'retired three-core wording returned');
assert(html.includes('content="https://qilylean.com/qilylean/c919-strategy-hero.png"'),'social C919 fallback image missing');
assert(html.includes('rel="preload" as="image" href="/qilylean/c919-strategy-hero-v10.svg" type="image/svg+xml"'),'corrected C919 preload missing');
console.log('C919 homepage hero guard passed: semantic left wing 1-3/right wing 4-6; visual screen stacks swapped; official QilyLean and exact Q icon patches locked.');