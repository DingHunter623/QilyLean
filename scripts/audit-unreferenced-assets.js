#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const root = path.resolve(__dirname, '..');
const reportFile = path.join(root, 'maintenance', 'unreferenced-assets-report.json');
const reportRepoPath = 'maintenance/unreferenced-assets-report.json';
const apply = process.argv.includes('--apply');

const assetExtensions = new Set([
  '.png', '.jpg', '.jpeg', '.webp', '.gif', '.bmp', '.tif', '.tiff', '.svg', '.ico',
  '.pdf', '.doc', '.docx', '.xls', '.xlsx', '.ppt', '.pptx',
  '.zip', '.rar', '.7z', '.apk', '.ipa',
  '.mp4', '.mov', '.m4v', '.webm', '.mp3', '.wav', '.m4a'
]);

const textExtensions = new Set([
  '.html', '.htm', '.css', '.js', '.mjs', '.cjs', '.json', '.md', '.txt', '.xml',
  '.yml', '.yaml', '.csv', '.ts', '.tsx', '.jsx', '.py', '.sh', '.ps1', '.toml',
  '.ini', '.conf', '.map', '.webmanifest', '.svg'
]);

const extensionPattern = Array.from(assetExtensions)
  .map((item) => item.slice(1).replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
  .join('|');
const assetTokenPattern = new RegExp(`\\.(?:${extensionPattern})(?:[?#][^\\s]*)?$`, 'i');
const tokenPattern = /[^\s"'`()<>{}]+/g;

/*
 * Only protect assets that are known to be runtime/source dependencies whose references
 * may be extension-less or generated by build tools. Public website media is deliberately
 * NOT blanket-protected: if no current page/script/data source references it, it is eligible
 * for cleanup. This is what allows stale daily artwork to be removed after weekly curation.
 */
const protectedPathPatterns = [
  /^assets\/brand\//i,
  /^android\//i,
  /^ios\//i,
  /^projects\/lean-improvement-evidence\//i,
  /(?:^|\/)(?:favicon|apple-touch-icon|site-icon|browserconfig)(?:[._-]|$)/i,
  /(?:^|\/)[^/]*(?:logo|brandmark|wechat|weixin|qrcode|qr-code|home-qr)[^/]*$/i
];

const ignoredReferenceSources = new Set([
  reportRepoPath.toLowerCase()
]);

function trackedFiles() {
  return execFileSync('git', ['ls-files', '-z'], {
    cwd: root,
    encoding: 'utf8',
    maxBuffer: 96 * 1024 * 1024
  })
    .split('\0')
    .filter(Boolean)
    .map((item) => item.replace(/\\/g, '/'));
}

function safeDecode(value) {
  try { return decodeURIComponent(value); } catch (_) { return value; }
}

function cleanReference(raw) {
  let value = String(raw || '').trim().replace(/\\/g, '/');
  if (value.includes('=')) value = value.slice(value.lastIndexOf('=') + 1);
  value = value.replace(/^[\s'"`(]+|[\s'"`),;]+$/g, '');
  value = value.split('#')[0].split('?')[0];
  value = safeDecode(value);
  if (!value || /^(?:data|mailto|tel|javascript):/i.test(value)) return null;

  if (/^https?:\/\//i.test(value)) {
    try {
      const url = new URL(value);
      if (!/(^|\.)qilylean\.com$/i.test(url.hostname)) return null;
      value = url.pathname;
    } catch (_) {
      return null;
    }
  }

  value = value.replace(/^\/+/, '').replace(/^\.\//, '');
  return value ? path.posix.normalize(value) : null;
}

function extractRawReferences(content) {
  const tokens = content.match(tokenPattern) || [];
  return tokens.filter((token) => assetTokenPattern.test(token));
}

function isProtectedCore(file) {
  return protectedPathPatterns.some((pattern) => pattern.test(file));
}

function humanBytes(bytes) {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(2)} KiB`;
  if (bytes < 1024 * 1024 * 1024) return `${(bytes / 1024 / 1024).toFixed(2)} MiB`;
  return `${(bytes / 1024 / 1024 / 1024).toFixed(2)} GiB`;
}

function main() {
  const files = trackedFiles();
  const textFiles = files.filter((file) => {
    if (ignoredReferenceSources.has(file.toLowerCase())) return false;
    return textExtensions.has(path.posix.extname(file).toLowerCase());
  });
  const candidates = files.filter((file) => assetExtensions.has(path.posix.extname(file).toLowerCase()));
  const candidateSet = new Set(candidates.map((file) => file.toLowerCase()));
  const basenameMap = new Map();

  candidates.forEach((file) => {
    const base = path.posix.basename(file).toLowerCase();
    if (!basenameMap.has(base)) basenameMap.set(base, []);
    basenameMap.get(base).push(file);
  });

  const directReferences = new Set();
  const basenameReferences = new Set();
  const referenceSources = new Map();

  textFiles.forEach((source) => {
    let content;
    try {
      content = fs.readFileSync(path.join(root, source), 'utf8');
    } catch (_) {
      return;
    }

    extractRawReferences(content).forEach((raw) => {
      const cleaned = cleanReference(raw);
      if (!cleaned) return;

      const variants = new Set([
        cleaned,
        path.posix.normalize(path.posix.join(path.posix.dirname(source), cleaned))
      ]);

      variants.forEach((variant) => {
        const key = variant.replace(/^(?:\.\.\/)+/, '').toLowerCase();
        if (!candidateSet.has(key)) return;
        directReferences.add(key);
        if (!referenceSources.has(key)) referenceSources.set(key, []);
        const sources = referenceSources.get(key);
        if (sources.length < 20 && !sources.includes(source)) sources.push(source);
      });

      basenameReferences.add(path.posix.basename(cleaned).toLowerCase());
    });
  });

  const deletable = [];
  const retained = [];

  candidates.forEach((file) => {
    const absolute = path.join(root, file);
    if (!fs.existsSync(absolute)) return;
    const stat = fs.statSync(absolute);
    const key = file.toLowerCase();
    const base = path.posix.basename(file).toLowerCase();
    const direct = directReferences.has(key);
    const uniqueBasename = (basenameMap.get(base) || []).length === 1;
    const basenameOnly = !direct && uniqueBasename && basenameReferences.has(base);
    const protectedCore = isProtectedCore(file);
    const referenced = direct || basenameOnly;

    const record = {
      path: file,
      bytes: stat.size,
      humanBytes: humanBytes(stat.size),
      reason: protectedCore
        ? 'protected-source-or-core-asset'
        : direct
          ? 'referenced-path'
          : basenameOnly
            ? 'referenced-unique-basename'
            : 'no-current-reference-found',
      sources: direct ? (referenceSources.get(key) || []) : []
    };

    if (!protectedCore && !referenced) deletable.push(record);
    else retained.push(record);
  });

  deletable.sort((a, b) => b.bytes - a.bytes || a.path.localeCompare(b.path));
  retained.sort((a, b) => a.path.localeCompare(b.path));

  const potentialBytes = deletable.reduce((sum, item) => sum + item.bytes, 0);
  const deletionRatio = candidates.length ? deletable.length / candidates.length : 0;
  const byteRatio = candidates.length
    ? potentialBytes / candidates.reduce((sum, file) => {
        try { return sum + fs.statSync(path.join(root, file)).size; } catch (_) { return sum; }
      }, 0)
    : 0;

  const report = {
    generatedAt: new Date().toISOString(),
    mode: apply ? 'apply' : 'audit',
    trackedFiles: files.length,
    scannedTextFiles: textFiles.length,
    assetFiles: candidates.length,
    retainedAssets: retained.length,
    unreferencedAssets: deletable.length,
    potentialBytesToRelease: potentialBytes,
    potentialReleaseHuman: humanBytes(potentialBytes),
    deletionRatioByCount: Number((deletionRatio * 100).toFixed(2)),
    deletionRatioByBytes: Number((byteRatio * 100).toFixed(2)),
    deletedAssets: 0,
    deletedBytes: 0,
    deletedHuman: '0 B',
    safetyStop: apply && (deletionRatio > 0.65 || byteRatio > 0.75),
    note: 'Current-branch cleanup only. Git history retains older blobs until a separate, explicitly approved history rewrite. The previous cleanup report is excluded from reference scanning to prevent self-reference contamination.',
    deletable,
    retained
  };

  fs.mkdirSync(path.dirname(reportFile), { recursive: true });
  fs.writeFileSync(reportFile, `${JSON.stringify(report, null, 2)}\n`, 'utf8');

  if (report.safetyStop) {
    throw new Error(`Safety stop: ${deletable.length}/${candidates.length} assets or ${report.deletionRatioByBytes}% of asset bytes were classified as unreferenced.`);
  }

  if (apply) {
    deletable.forEach((item) => {
      const target = path.join(root, item.path);
      if (!fs.existsSync(target)) return;
      fs.unlinkSync(target);
      report.deletedAssets += 1;
      report.deletedBytes += item.bytes;
    });
    report.deletedHuman = humanBytes(report.deletedBytes);
    fs.writeFileSync(reportFile, `${JSON.stringify(report, null, 2)}\n`, 'utf8');
  }

  process.stdout.write(`${apply ? 'Deleted' : 'Found'} ${apply ? report.deletedAssets : deletable.length} unreferenced assets; ${apply ? report.deletedHuman : report.potentialReleaseHuman}.\n`);
}

main();
